    print(f'«{nombre}» | picos detectados en (Δu, Δv) = (freq. horizontal, vertical), en px: {coords}  '
          f'(el patrón varía en x con f = 0.1 ciclos/px ⇒ Δu ≈ ±{0.1*N:.0f}, Δv = 0 para N={N})')

