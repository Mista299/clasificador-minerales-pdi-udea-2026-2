# ---- Utilidades del dominio de la frecuencia (Módulo D) ----
def fft_c(img):
    # FFT 2D centrada (frecuencia cero en el centro del espectro)
    return np.fft.fftshift(np.fft.fft2(np.asarray(img, np.float64)))

def ifft_c(F):
    # Inversa de fft_c (devuelve array complejo; tomar parte real)
    return np.fft.ifft2(np.fft.ifftshift(F))

def malla_D(shape):
    # Distancia radial D(u,v) a la frecuencia cero, en "píxeles de frecuencia"
    M, N = shape
    fy = np.fft.fftshift(np.fft.fftfreq(M))*M      # frecuencia vertical centrada
    fx = np.fft.fftshift(np.fft.fftfreq(N))*N      # frecuencia horizontal centrada
    FX, FY = np.meshgrid(fx, fy)
    return np.hypot(FX, FY)

def espectro_log(F):
    # Magnitud del espectro en escala logarítmica, lista para mostrar (Módulo C.2)
    m = np.log1p(np.abs(F))
    return a_uint8(255*m/m.max())

